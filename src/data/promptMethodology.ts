export interface MethodologyLaw {
  /** id لنگر، مثلاً "law-1" */
  id: string;
  /** شماره ۱ تا ۱۲ */
  index: number;
  /** عنوان کامل (پس از خط تیره شامل زیرعنوان) */
  title: string;
  /** عنوان کوتاه، برای فهرست و برچسب گوشه کارت */
  shortTitle: string;
  /** زیرعنوان یک‌جمله‌ای (محتوای پس از خط تیره) */
  subtitle: string;
  /** کلید آیکون */
  icon: MethodologyIcon;
  /** چه مشکلی را حل می‌کند —— پاراگراف مقدمه */
  problem: string;
  /** چه مشکلی را حل می‌کند —— نکات تفکیکی اختیاری */
  problemPoints?: string[];
  /** قالب قابل استفاده مجدد (متن اصلی، رندر با فونت هم‌عرض) */
  template: string;
  /** نمونه‌های شاخص */
  cases: MethodologyCase[];
  /** نباید کپی شود */
  cautions: string[];
}

export interface MethodologyPattern {
  /** id لنگر */
  id: string;
  /** حرف الگو، مثلاً "A" */
  letter: string;
  /** نام الگو */
  title: string;
  /** منبع */
  source: string;
  /** متن توضیح */
  body: string;
  /** بلوک کد نمونه اختیاری */
  example?: string;
}

export interface MethodologyChecklistItem {
  /** نام بُعد، مثلاً "هویت" */
  dimension: string;
  /** سؤال خودارزیابی */
  question: string;
}

